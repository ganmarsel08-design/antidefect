// Этап 8 — привязка явно указанных даты и времени к событию (ответ рецензента 2 от 26.11 11:49 UTC).
// Подтверждение unknown/document_time не ослабляется: event_time — только когда явные дата и время стоят сразу после
// глагола действия, во фразе одна отметка времени и нет плана/условия/отрицания/неопределённости/другого пациента/результата.
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const X = require('../extract/extract.js');
const bc = t => X.extract(t, { tz: '+05:00' }).candidates.filter(c => c.field === 'blood_culture_drawn_at').map(c => [c.value === undefined ? null : c.value, c.time_basis]);
const fd = t => X.extract(t, { tz: '+05:00' }).candidates.filter(c => c.field === 'first_abx_dose_administered_at').map(c => [c.value, c.time_basis]);

test('явное время сразу после действия → event_time (и при заголовке записи с другим временем)', () => {
  assert.deepEqual(bc('Кровь на посев взята 02.03.2026 07:30.'), [['2026-03-02T07:30+05:00', 'event_time']]);
  assert.deepEqual(bc('02.03.2026 06:00 — Кровь на посев взята 02.03.2026 07:30.'), [['2026-03-02T07:30+05:00', 'event_time']]);
  assert.deepEqual(fd('Первая доза ампициллина введена 02.03.2026 07:50.'), [['2026-03-02T07:50+05:00', 'event_time']]);
});
test('время только в заголовке записи — по-прежнему unknown (подтверждение не ослаблено)', () => {
  assert.deepEqual(bc('02.03.2026 07:30 — кровь на посев взята.'), [['2026-03-02T07:30+05:00', 'unknown']]);
});
test('два действия и два времени: каждому своё время, не перепутаны', () => {
  const t = 'Кровь на посев взята 02.03.2026 07:30. Первая доза ампициллина введена 02.03.2026 07:50.';
  assert.deepEqual(bc(t), [['2026-03-02T07:30+05:00', 'event_time']]);
  assert.deepEqual(fd(t), [['2026-03-02T07:50+05:00', 'event_time']]);
  // в одной фразе через запятую — консервативно unknown, но значения свои
  const u = 'Кровь на посев взята 02.03.2026 07:30, первая доза ампициллина введена 02.03.2026 07:50.';
  assert.deepEqual(bc(u), [['2026-03-02T07:30+05:00', 'unknown']]);
  assert.deepEqual(fd(u), [['2026-03-02T07:50+05:00', 'unknown']]);
});
test('план / условие, неопределённость, другой пациент, время результата — не event_time', () => {
  assert.deepEqual(bc('При ухудшении кровь на посев взята 02.03.2026 07:30.'), [['2026-03-02T07:30+05:00', 'unknown']]);
  assert.deepEqual(bc('Кровь на посев взята 02.03.2026 07:30? уточнить.'), [['2026-03-02T07:30+05:00', 'unknown']]);
  assert.deepEqual(bc('У матери кровь на посев взята 02.03.2026 07:30.'), [['2026-03-02T07:30+05:00', 'unknown']]);
  assert.deepEqual(bc('02.03.2026 06:00 — Кровь на посев взята 02.03.2026 07:30, результат 03.03.2026 10:00.'), [['2026-03-02T07:30+05:00', 'unknown']]);
  assert.deepEqual(bc('Результат посева от 03.03.2026 10:00: кровь на посев взята 02.03.2026 07:30.'), [['2026-03-02T07:30+05:00', 'unknown']]);
});
test('копия и исправление', () => {
  assert.deepEqual(bc('Скопировано: кровь на посев взята 02.03.2026 07:30.'), []);
  const r = bc('Ошибочно указано: кровь на посев взята 02.03.2026 07:30, верно: кровь на посев взята 02.03.2026 07:50.');
  assert.deepEqual(r.map(x => x[0]), ['2026-03-02T07:50+05:00'], 'ошибочное значение убрано');
  assert.notEqual(r[0][1], 'document_time');
});
test('полночь: явная дата следующих суток после заголовка накануне', () => {
  assert.deepEqual(bc('02.03.2026 23:50 — Кровь на посев взята 03.03.2026 00:10.'), [['2026-03-03T00:10+05:00', 'event_time']]);
});

test('ревью 061a087: «ребенка» без ё, отрицание/сомнение/«уточнить» после даты, условие после «;»', () => {
  const unk = t => assert.deepEqual(bc(t).map(x => x[1]).filter(x => x === 'event_time'), [], t);
  unk('У другого ребенка кровь на посев взята 02.03.2026 07:30.');
  unk('У соседнего ребёнка кровь на посев взята 02.03.2026 07:30.');
  unk('Кровь на посев взята 02.03.2026 07:30, не подтверждено.');
  unk('Кровь на посев взята 02.03.2026 07:30, уточнить.');
  unk('Кровь на посев взята 02.03.2026 07:30 уточнить время.');
  unk('Кровь на посев взята 02.03.2026 07:30; при ухудшении повторить.');
  unk('Кровь на посев взята 02.03.2026 07:30, отменено.');
  unk('Кровь на посев взята 02.03.2026 07:30, у матери.');
  // положительный контроль не сломан
  assert.deepEqual(bc('Кровь на посев взята 02.03.2026 07:30.'), [['2026-03-02T07:30+05:00', 'event_time']]);
  // чужое/сомнительное не уходит в текущего пациента как event_time и значение не теряется молча
  const r = bc('У другого ребенка кровь на посев взята 02.03.2026 07:30.');
  assert.ok(r.every(x => x[1] !== 'event_time'));
});

test('ревью 8158324: хвост после «;» — результат, ответ, второе время без маркера → не event_time; два самостоятельных предложения — event_time', () => {
  const nz = t => assert.deepEqual(bc(t).filter(x => x[1] === 'event_time'), [], t);
  nz('Кровь на посев взята 02.03.2026 07:30; результат 03.03.2026 10:00.');
  nz('Кровь на посев взята 02.03.2026 07:30; ответ получен.');
  nz('Кровь на посев взята 02.03.2026 07:30; повторно 02.03.2026 15:00.');
  nz('Кровь на посев взята 02.03.2026 07:30, 02.03.2026 15:00 — повтор.');
  assert.deepEqual(bc('Кровь на посев взята 02.03.2026 07:30. Результат 03.03.2026 10:00.'), [['2026-03-02T07:30+05:00', 'event_time']]);
  assert.deepEqual(bc('Кровь на посев взята 02.03.2026 07:30. Повторно 02.03.2026 15:00 — ухудшение.'), [['2026-03-02T07:30+05:00', 'event_time']]);
});

test('запись названа ошибочной после времени — не event_time (самостоятельный поиск ошибок 27.11)', () => {
  for (const t of ['Кровь на посев взята 02.03.2026 07:30 — ошибочная запись, см. исправление.',
                   'Кровь на посев взята 02.03.2026 07:30 (запись внесена ошибочно).',
                   'Кровь на посев взята 02.03.2026 07:30; запись неверна.',
                   'Кровь на посев взята 02.03.2026 07:30 — запись аннулирована.']) {
    assert.ok(!bc(t).some(([, tb]) => tb === 'event_time'), t);
  }
  // контроль: без пометки — по-прежнему event_time
  assert.deepEqual(bc('Кровь на посев взята 02.03.2026 07:30.'), [['2026-03-02T07:30+05:00', 'event_time']]);
});
