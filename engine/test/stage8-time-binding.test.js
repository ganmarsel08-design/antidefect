// Этап 8 — привязка времени к событию (ошибка СЛП-НЭК-03 из слепого теста №1). Только синтетические данные.
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const X = require('../extract/extract.js');
const TZ = '+05:00';
const get = (t, f) => X.extract(t, { tz: TZ }).candidates.find(c => c.field === f);

test('время в том же предложении важнее времени заголовка записи (НЭК-03)', () => {
  const t = '22.06.2026 08:30 — Вздутие живота. Подозрение на НЭК. Энтеральное кормление прекращено в 08:40, установлен назогастральный зонд.';
  const c = get(t, 'enteral_feeding_stopped_at');
  assert.equal(c.value, '2026-06-22T08:40+05:00');
  assert.equal(get(t, 'nec_suspected_at').value, '2026-06-22T08:30+05:00');
  for (const f of c.fragments) { assert.equal(t.slice(f.start, f.end), f.text); assert.match(f.text, /08:40/); assert.match(f.text, /прекращено/); }
});

test('нет своего времени в предложении — время заголовка записи (как раньше)', () => {
  const c = get('22.06.2026 08:30 — Вздутие живота. Кормление прекращено, установлен зонд.', 'enteral_feeding_stopped_at');
  assert.equal(c.value, '2026-06-22T08:30+05:00');
});

test('два разных времени в одном предложении — значения нет (не угадываем)', () => {
  const t = '22.06.2026 08:30 — Осмотр. Кормление прекращено в 08:40 или в 08:45.';
  assert.equal(get(t, 'enteral_feeding_stopped_at'), undefined);
  assert.ok(get(t, 'enteral_feeding_stopped'), 'сам факт прекращения извлекается');
});

test('время раньше заголовка (возможен переход через полночь) — значения нет', () => {
  const t = '22.06.2026 23:50 — Ухудшение. Кормление прекращено в 00:10.';
  assert.equal(get(t, 'enteral_feeding_stopped_at'), undefined);
});

test('полная дата-время в предложении используется как есть', () => {
  const t = '22.06.2026 23:50 — Ухудшение. Кормление прекращено 23.06.2026 00:10.';
  assert.equal(get(t, 'enteral_feeding_stopped_at').value, '2026-06-23T00:10+05:00');
});

test('время без даты и без заголовка — значения нет', () => {
  assert.equal(get('Кормление прекращено в 08:40.', 'enteral_feeding_stopped_at'), undefined);
});

test('отрицание не даёт времени прекращения', () => {
  const t = '22.06.2026 08:30 — Кормление не прекращено в 08:40.';
  assert.equal(get(t, 'enteral_feeding_stopped_at'), undefined);
  assert.equal(get(t, 'enteral_feeding_stopped').value, false);
});

test('время в соседнем предложении не переносится на событие', () => {
  const t = '22.06.2026 08:30 — Контроль СРБ в 09:15. Кормление прекращено.';
  assert.equal(get(t, 'enteral_feeding_stopped_at').value, '2026-06-22T08:30+05:00');
});

test('дробные числа и дозы не принимаются за время', () => {
  const t = '22.06.2026 08:30 — Кормление прекращено, объём 12.30 мл, интервал 3 ч.';
  assert.equal(get(t, 'enteral_feeding_stopped_at').value, '2026-06-22T08:30+05:00');
});

test('время после «назначена в», «через», «после» не считается временем события', () => {
  const t = '04.08.2026 10:50 — Введена первая доза эмпирической АБТ по схеме бензилпенициллин + гентамицин (назначена в 10:25).';
  assert.equal(get(t, 'first_abx_dose_administered_at').value, '2026-08-04T10:50+05:00');
});

test('дата из заголовка раздела для записей «ЧЧ:ММ —»', () => {
  const t = 'Дневник 14.01.2026\n07:00 — Осмотр. В 07:30 введена первая доза антибиотиков.\n18:00 — Кормление прекращено.';
  assert.equal(get(t, 'first_abx_dose_administered_at').value, '2026-01-14T07:30+05:00');
  assert.equal(get(t, 'enteral_feeding_stopped_at').value, '2026-01-14T18:00+05:00');
});

test('переход через полночь под одной датой раздела — дата больше не подставляется', () => {
  const t = 'Дневник 14.01.2026\n23:30 — Осмотр.\n00:20 — Кормление прекращено.';
  assert.equal(get(t, 'enteral_feeding_stopped_at'), undefined);
});

test('заголовок раздела с диапазоном дат не задаёт дату', () => {
  const t = 'Течение (01.07.2026 – 07.07.2026)\n09:00 — Кормление прекращено.';
  assert.equal(get(t, 'enteral_feeding_stopped_at'), undefined);
});

test('форматы даты: ДД/ММ/ГГГГ, ДД.ММ.ГГ, «в» между датой и временем', () => {
  assert.equal(get('11/02/2026 14:20 — Кормление прекращено.', 'enteral_feeding_stopped_at').value, '2026-02-11T14:20+05:00');
  assert.equal(get('03.02.26 09:30 — Кормление прекращено.', 'enteral_feeding_stopped_at').value, '2026-02-03T09:30+05:00');
  assert.equal(get('Осмотр. Кормление прекращено 10.05.2026 в 09:00.', 'enteral_feeding_stopped_at').value, '2026-05-10T09:00+05:00');
});

// Ревью ChatGPT к PR №12: время одного действия не переносится на другое в той же записи.
test('«Кормление прекращено, зонд установлен в 08:50» — 08:50 не приписывается кормлению', () => {
  const t = '22.06.2026 08:30 — Кормление прекращено, зонд установлен в 08:50.';
  assert.equal(get(t, 'enteral_feeding_stopped_at'), undefined, 'ни 08:50, ни время заголовка 08:30');
  assert.equal(get(t, 'enteral_feeding_stopped').value, true);
});
test('«Кормление прекращено, в 08:50 установлен зонд» — 08:50 не приписывается кормлению', () => {
  assert.equal(get('22.06.2026 08:30 — Кормление прекращено, в 08:50 установлен зонд.', 'enteral_feeding_stopped_at'), undefined);
});
test('«В 08:40 прекращено кормление, зонд установлен» / «Кормление прекращено в 08:40, установлен зонд» — 08:40 кормлению', () => {
  assert.equal(get('22.06.2026 08:30 — Кормление прекращено в 08:40, установлен назогастральный зонд.', 'enteral_feeding_stopped_at').value, '2026-06-22T08:40+05:00');
});
test('без запятой: «Кормление прекращено и зонд установлен в 08:50» — 08:50 не приписывается кормлению', () => {
  assert.equal(get('22.06.2026 08:30 — Кормление прекращено и зонд установлен в 08:50.', 'enteral_feeding_stopped_at'), undefined);
  assert.equal(get('22.06.2026 08:30 — Кормление прекращено — зонд установлен в 08:50.', 'enteral_feeding_stopped_at'), undefined);
});
test('зонд со своим временем получает своё время, кормление — нет', () => {
  const t = '22.06.2026 08:30 — Кормление прекращено, установлен назогастральный зонд в 08:50.';
  assert.equal(get(t, 'ng_tube_placed_at').value, '2026-06-22T08:50+05:00');
  assert.equal(get(t, 'enteral_feeding_stopped_at'), undefined);
});
test('время в соседнем предложении не мешает и не переносится', () => {
  const t = '22.06.2026 08:30 — Зонд установлен в 08:50. Кормление прекращено.';
  assert.equal(get(t, 'enteral_feeding_stopped_at').value, '2026-06-22T08:30+05:00');
});
test('время в скобках относится к скобкам', () => {
  const t = '19.03.2026 10:00 — Посев крови отрицательный (получен 19.03.2026 09:30), антибиотики отменены.';
  assert.equal(get(t, 'antibiotics_stopped_at').value, '2026-03-19T10:00+05:00', '09:30 — время результата посева; отмене остаётся время записи');
});
